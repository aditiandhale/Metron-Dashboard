// ---------------------------------------------------------------------------
// Everything below is logic, not data. You normally never need to edit it.
// It turns the static data above into the final payload (adds id, symbol, logo,
// grid position, counts, colors). Add a new key to the returned object whenever
// you want to expose something new, and every file gets it through `payload`.
// For a runtime database later: fetch the same shape and call buildPayload(fetched).
// ---------------------------------------------------------------------------
function buildPayload(data) {
  const toSymbol = (n) => {
    const w = n.split(/\s+/);
    return w.length > 1
      ? (w[0][0] + w[1][0]).toUpperCase()
      : n[0].toUpperCase() + (n[1] || "").toLowerCase();
  };
  const sum = (a) => a.reduce((x, y) => x + y, 0);

  const names = [...new Set(data.integrations.map((i) => i.category))];
  const color = (c) => data.colors[names.indexOf(c) % data.colors.length];

  // group by category so tiles stay ordered category by category
  const entries = names.flatMap((category) =>
    data.integrations
      .filter((i) => i.category === category)
      .map(({ name, domain, description, pros, cons }) => ({
        id: `${category}:${name}`,
        name,
        category,
        description,
        symbol: toSymbol(name),
        logo: domain
          ? `https://www.google.com/s2/favicons?domain=${domain}&sz=128`
          : "",
        pros,
        cons,
      })),
  );

  // Diagram shape: relative column heights, scaled to the number of integrations.
  const profile = [10, 9, 6, 6, 6, 6, 4, 4, 4, 4, 4, 6, 6, 6, 6, 6, 8, 10];
  const heights = profile.map((p) =>
    Math.max(1, Math.round((p * entries.length) / sum(profile))),
  );
  for (
    let i = 0, d = entries.length - sum(heights);
    d !== 0;
    i = (i + 1) % heights.length
  ) {
    const step = Math.sign(d);
    if (heights[i] + step >= 1) {
      heights[i] += step;
      d -= step;
    }
  }
  const rows = Math.max(...heights);
  const cells = heights.flatMap((h, col) =>
    Array.from({ length: h }, (_, i) => ({ col, row: rows - h + i })),
  );

  return {
    colors: data.colors,
    names, // category names
    color, // color(category) -> hex
    integrations: entries.map((e, i) => ({ ...e, ...cells[i] })), // tiles with col/row
    counts: Object.fromEntries(
      names.map((c) => [c, entries.filter((e) => e.category === c).length]),
    ), // integrations per category
    panelRows: Math.max(
      1,
      Math.min(...heights.slice(2, 16).map((h) => rows - h)),
    ), // rows reserved for the side panel
  };
}
